{- |
Python classes with Haskell payloads.

The Haskell payload type /is/ the Python type tag, so an instance of the class
@Counter@ is @'Bound' π Counter@.
The object holds a stable pointer to the payload and one word of lend state,
PyO3's borrow flag, in type data reached through @PyObject_GetTypeData@.
A dereference turns a borrow of the object into a borrow of its payload, in
place, at the ambient lifetime, and the hold it takes is released when the
arena that took it is swept.
See section 5.3 of the design.
-}
module H2Py.Class.Internal (
  module H2Py.Class.Internal,
) where

